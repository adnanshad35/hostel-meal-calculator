import 'dart:async';

import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_auth/firebase_auth.dart';

import 'super_admin_service.dart';

/// Something shown in a notification list: an app-wide notice, an
/// announcement from a hostel admin, or an event inside a hostel.
class AppNotification {
  const AppNotification({
    required this.id,
    required this.title,
    required this.message,
    required this.createdAt,
    required this.isAnnouncement,
    this.actorId,
  });

  factory AppNotification.fromDocument(
    DocumentSnapshot<Map<String, dynamic>> document, {
    bool? isAnnouncement,
  }) {
    final data = document.data() ?? const <String, dynamic>{};

    return AppNotification(
      id: document.id,
      title: data['title'] as String? ?? '',
      message: data['message'] as String? ?? '',
      // A notification that is still being saved has no server time
      // yet, so it counts as happening now.
      createdAt: (data['createdAt'] as Timestamp?)?.toDate() ?? DateTime.now(),
      isAnnouncement: isAnnouncement ?? data['type'] == 'announcement',
      actorId: data['actorId'] as String?,
    );
  }

  final String id;
  final String title;
  final String message;
  final DateTime createdAt;

  /// Written by a person (the developer or a hostel admin), as opposed
  /// to generated by an action such as adding an expense.
  final bool isAnnouncement;

  /// The member who wrote the announcement or caused the event.
  final String? actorId;
}

/// In-app notifications. They appear while the app is open and the
/// next time it is opened; nothing is delivered while it is closed.
///
/// There are two separate lists: app notices for every user, shown on
/// the home screen, and hostel notifications, shown inside a hostel.
class NotificationService {
  NotificationService._();

  /// Hostel announcements are limited to this many words.
  static const int maxAnnouncementWords = 50;

  static FirebaseFirestore get _firestore => FirebaseFirestore.instance;

  static CollectionReference<Map<String, dynamic>> get _appNotices =>
      _firestore.collection('announcements');

  static CollectionReference<Map<String, dynamic>> _groupNotifications(
    String groupId,
  ) {
    return _firestore
        .collection('groups')
        .doc(groupId)
        .collection('notifications');
  }

  /// Only the super admin may send app notices to every user.
  static bool get isDeveloper => SuperAdminService.isSuperAdmin;

  static int wordCount(String text) {
    return text
        .trim()
        .split(RegExp(r'\s+'))
        .where((word) => word.isNotEmpty)
        .length;
  }

  static Stream<List<AppNotification>> _watch(
    Query<Map<String, dynamic>> query, {
    bool? isAnnouncement,
  }) {
    return query.snapshots().map(
      (snapshot) => [
        for (final document in snapshot.docs)
          AppNotification.fromDocument(
            document,
            isAnnouncement: isAnnouncement,
          ),
      ],
    );
  }

  /// App notices for every user, newest first.
  static Stream<List<AppNotification>> watchApp() {
    return _watch(
      _appNotices.orderBy('createdAt', descending: true).limit(30),
      isAnnouncement: true,
    );
  }

  /// A hostel's announcements and activity, newest first.
  static Stream<List<AppNotification>> watchGroup(String groupId) {
    return _watch(
      _groupNotifications(groupId)
          .orderBy('createdAt', descending: true)
          .limit(50),
    );
  }

  /// How many [items] arrived after [seenAt]. A member's own actions
  /// never count as unread for them.
  static int unreadCount(
    List<AppNotification> items, {
    required DateTime? seenAt,
    required String currentUserId,
  }) {
    return items.where((item) {
      if (item.actorId == currentUserId) return false;
      return seenAt == null || item.createdAt.isAfter(seenAt);
    }).length;
  }

  /// The newest item written after [seenAt], if any.
  static AppNotification? newestUnseen(
    List<AppNotification> items, {
    required DateTime? seenAt,
  }) {
    for (final item in items) {
      if (seenAt == null || item.createdAt.isAfter(seenAt)) return item;
    }

    return null;
  }

  /// The user-document field that stores when a list was last opened.
  static String seenField({required bool isGroup}) {
    return isGroup ? 'groupNotificationsSeenAt' : 'appNoticesSeenAt';
  }

  static Future<void> markSeen({required bool isGroup}) async {
    final user = FirebaseAuth.instance.currentUser;
    if (user == null) return;

    try {
      await _firestore.collection('users').doc(user.uid).set({
        seenField(isGroup: isGroup): FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));
    } on FirebaseException {
      // The badge simply stays until the next successful attempt.
    }
  }

  /// Sends a notice to every user of the app. Developer only.
  static Future<void> sendAppNotice({
    required String title,
    required String message,
  }) async {
    await _appNotices.add({
      'title': title.trim(),
      'message': message.trim(),
      'createdBy': FirebaseAuth.instance.currentUser!.uid,
      'createdAt': FieldValue.serverTimestamp(),
    });
  }

  static Future<void> deleteAppNotice(String id) {
    return _appNotices.doc(id).delete();
  }

  /// Posts an announcement to everyone in a hostel. Admins only.
  static Future<void> sendGroupAnnouncement({
    required String groupId,
    required String message,
  }) async {
    final user = FirebaseAuth.instance.currentUser!;
    final name = user.displayName?.trim();

    await _groupNotifications(groupId).add({
      'type': 'announcement',
      'title': name == null || name.isEmpty
          ? 'Announcement'
          : 'Announcement from $name',
      'message': message.trim(),
      'actorId': user.uid,
      'createdAt': FieldValue.serverTimestamp(),
    });
  }

  static Future<void> deleteGroupNotification({
    required String groupId,
    required String id,
  }) {
    return _groupNotifications(groupId).doc(id).delete();
  }

  /// Tells the other members of a hostel that an expense was added.
  /// Best effort: a failure never blocks the action that caused it.
  static Future<void> notifyGroup({
    required String groupId,
    required String title,
    required String message,
  }) async {
    final user = FirebaseAuth.instance.currentUser;
    if (user == null) return;

    try {
      await _groupNotifications(groupId).add({
        'type': 'expense',
        'title': title,
        'message': message,
        'actorId': user.uid,
        'createdAt': FieldValue.serverTimestamp(),
      });
    } on FirebaseException {
      // Ignored on purpose.
    }
  }
}
